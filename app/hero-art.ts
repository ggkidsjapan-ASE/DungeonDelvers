// Letters: C/c torso, A/a arms, L/l legs, H/h head (lowercase is the shaded tone), T/t trim,
// S/s skin, B/b leather, K black, M steel, W white, E eye.
function reversed(row: string) { return Array.from(row).reverse().join(""); }
/** Mirrors the left half of a piece onto the right, so pairs of arms and legs stay symmetrical. */
function mirrored(rows: string[], gap = 0) {
  return rows.map((row) => row + ".".repeat(gap) + reversed(row));
}

