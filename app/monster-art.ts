// Creator monsters are assembled on a 40 x 40 grid, and each piece gets a black outline from PixelGrid.
// Saved monsters store these option names, so keep them in sync with BODY_PART_OPTIONS.
// Don't add parts that recreate the hand-drawn bosses in bosses.ts (crowns, giant single eyes, chests, plants).
export const MONSTER_VIEW_BOX = "0 0 40 40";

// Letters: H/h head, C/c torso, A/a arms, L/l legs, G/g tail, V/v wings (lowercase is the shaded tone),
// T/t trim, K black, W white, F fang, Y eye glow, O/o flame.
function reversed(row: string) { return Array.from(row).reverse().join(""); }
function mirrored(rows: string[], gap = 0) {
  return rows.map((row) => row + ".".repeat(gap) + reversed(row));
}

