const FALLBACK = { head: "beast", torso: "scaled", arms: "claws", legs: "talons" };

export function monsterLayers(parts: BodyParts, color: string, trimColor: string, colors?: PartColors): PixelLayer[] {
  const part = (name: keyof PartColors) => colors?.[name] || color;
  const palette = {
    H: part("head"), h: shade(part("head")), C: part("torso"), c: shade(part("torso")),
    A: part("arms"), a: shade(part("arms")), L: part("legs"), l: shade(part("legs")),
    G: part("tail"), g: shade(part("tail")), V: part("wings"), v: shade(part("wings")),
    T: trimColor, t: shade(trimColor), K: "#000000", W: "#f7f3e6", F: "#f4f1e6", Y: "#ffe45c", O: "#ee6a1f", o: "#b53a12",
  };
  const pieces = [
    parts.wings && WINGS[parts.wings],
    parts.tail && TAILS[parts.tail],
    LEGS[parts.legs] || LEGS[FALLBACK.legs],
    TORSOS[parts.torso] || TORSOS[FALLBACK.torso],
    ARMS[parts.arms] || ARMS[FALLBACK.arms],
    HEADS[parts.head] || HEADS[FALLBACK.head],
  ].filter((piece): piece is Part => !!piece);
  return pieces.map((piece) => ({ ...piece, palette }));
}
