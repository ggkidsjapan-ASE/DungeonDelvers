import type { SVGProps } from "react";

// Pixel-art interface icons on a 12 x 12 grid, drawn in the current text colour.
type IconProps = SVGProps<SVGSVGElement>;

function icon(rows: string[]) {
  let path = "";
  rows.forEach((row, y) => {
    for (const match of row.matchAll(/X+/g)) path += `M${match.index} ${y}h${match[0].length}v1h-${match[0].length}z`;
  });
  return function PixelIcon(props: IconProps) {
    return <svg width={24} height={24} viewBox="0 0 12 12" fill="currentColor" shapeRendering="crispEdges" aria-hidden="true" {...props}><path d={path} /></svg>;
  };
}

